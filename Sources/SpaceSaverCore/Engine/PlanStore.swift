import Foundation

/// A cleanup an AI agent asked for through MCP. Agents can only propose; a person approves
/// in the SpaceSaver app, and only then does anything move.
public struct CleanupPlan: Codable, Identifiable, Hashable, Sendable {
    public enum Status: String, Codable, Sendable {
        case pending, approved, rejected, executed, failed, expired
    }

    public struct Entry: Codable, Hashable, Sendable {
        public var path: String
        public var size: Int64
        public var risk: RiskLevel
        public var explanation: String
    }

    public var id: String
    public var created: Date
    public var requester: String
    public var reason: String
    public var entries: [Entry]
    public var status: Status
    public var decidedAt: Date?
    public var result: String?

    public var totalSize: Int64 { entries.reduce(0) { $0 + $1.size } }
    public var highestRisk: RiskLevel { entries.map(\.risk).max() ?? .safe }

    public func asCleanupItems(home: String = NSHomeDirectory()) -> [CleanupItem] {
        entries.map {
            CleanupItem(id: "plan:\(id):\($0.path)", category: .custom, title: Paths.name($0.path),
                        subtitle: Paths.abbreviate($0.path, home: home), paths: [$0.path], size: $0.size, risk: $0.risk,
                        explanation: $0.explanation, recommended: true)
        }
    }
}

public final class PlanStore: @unchecked Sendable {
    public let dir: String

    public init(paths: AppPaths = .default) {
        paths.ensure()
        dir = paths.plans
    }

    public init(directory: String) {
        dir = directory
        try? FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
    }

    private func file(_ id: String) -> String { Paths.join(dir, "\(id).json") }

    public func all() -> [CleanupPlan] {
        Paths.children(dir).filter { $0.hasSuffix(".json") }
            .compactMap { JSONStore.load(CleanupPlan.self, from: Paths.join(dir, $0)) }
            .map(expireIfStale)
            .sorted { $0.created > $1.created }
    }

    public func pending() -> [CleanupPlan] { all().filter { $0.status == .pending } }

    public func get(_ id: String) -> CleanupPlan? {
        // ids are generated by us; refuse anything that could walk out of the directory.
        guard id.allSatisfy({ $0.isLetter || $0.isNumber || $0 == "-" }) else { return nil }
        return JSONStore.load(CleanupPlan.self, from: file(id)).map(expireIfStale)
    }

    public func save(_ plan: CleanupPlan) throws {
        try JSONStore.save(plan, to: file(plan.id))
    }

    public func create(requester: String, reason: String, entries: [CleanupPlan.Entry]) throws -> CleanupPlan {
        let id = "plan-" + UUID().uuidString.prefix(8).lowercased()
        let plan = CleanupPlan(id: id, created: Date(), requester: requester.sanitizedForDisplay.prefix(80).description,
                               reason: reason.sanitizedForDisplay.prefix(500).description,
                               entries: entries, status: .pending)
        try save(plan)
        return plan
    }

    public func decide(_ id: String, status: CleanupPlan.Status, result: String? = nil) {
        guard var plan = get(id) else { return }
        plan.status = status
        plan.decidedAt = Date()
        plan.result = result
        try? save(plan)
    }

    /// Unanswered requests expire after 24 hours so a stale agent request can't be approved by accident.
    private func expireIfStale(_ plan: CleanupPlan) -> CleanupPlan {
        guard plan.status == .pending, Date().timeIntervalSince(plan.created) > 86_400 else { return plan }
        var p = plan
        p.status = .expired
        try? save(p)
        return p
    }
}
